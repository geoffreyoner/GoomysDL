// ==UserScript==
// @name         Goomys/DL - Instagram Cookie Export
// @namespace    https://github.com/geoffreyoner/GoomysDL
// @version      1.0.0
// @description  Export instagram.com cookies as a Netscape cookies.txt for yt-dlp / Goomys/DL.
// @author       geoffreyoner
// @match        https://www.instagram.com/*
// @match        https://instagram.com/*
// @grant        GM_cookie
// @grant        GM.cookie
// @run-at       document-idle
// @noframes
// ==/UserScript==

(() => {
  'use strict';

  const DOMAINS = ['https://www.instagram.com/', 'https://instagram.com/'];

  async function listCookies(details) {
    if (typeof GM !== 'undefined' && GM.cookie && GM.cookie.list) {
      return await GM.cookie.list(details);
    }
    if (typeof GM_cookie !== 'undefined' && GM_cookie.list) {
      return await new Promise((resolve, reject) => {
        GM_cookie.list(details, (cookies, error) => {
          if (error) reject(new Error(error));
          else resolve(cookies || []);
        });
      });
    }
    throw new Error('GM_cookie tidak tersedia. Pakai Tampermonkey atau Violentmonkey.');
  }

  function clean(value) {
    return String(value == null ? '' : value).replace(/[\t\r\n]/g, '');
  }

  function toNetscape(cookies) {
    const lines = [
      '# Netscape HTTP Cookie File',
      '# https://curl.se/docs/http-cookies.html',
      '# Generated by Goomys/DL Instagram Cookie Export',
      '',
    ];
    for (const c of cookies) {
      if (!c || !c.name) continue;
      const domain = clean(c.domain);
      lines.push([
        domain,
        domain.startsWith('.') ? 'TRUE' : 'FALSE',
        clean(c.path) || '/',
        c.secure ? 'TRUE' : 'FALSE',
        c.expirationDate ? Math.floor(c.expirationDate) : 0,
        clean(c.name),
        clean(c.value),
      ].join('\t'));
    }
    return `${lines.join('\n')}\n`;
  }

  function download(text) {
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'instagram-cookies.txt';
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  const button = document.createElement('button');
  button.type = 'button';
  button.textContent = 'Export cookies.txt';
  button.title = 'Instagram cookies untuk yt-dlp / Goomys/DL';
  Object.assign(button.style, {
    position: 'fixed',
    right: '16px',
    bottom: '16px',
    zIndex: '2147483647',
    padding: '10px 14px',
    border: '1px solid #444',
    borderRadius: '999px',
    background: '#111',
    color: '#eee',
    font: '600 12px system-ui, sans-serif',
    cursor: 'pointer',
    opacity: '0.85',
  });

  async function exportCookies() {
    const previous = button.textContent;
    button.disabled = true;
    button.textContent = 'Membaca cookie...';
    try {
      const results = await Promise.all(
        DOMAINS.map((url) => listCookies({ url }).catch(() => [])),
      );
      const seen = new Set();
      const cookies = [];
      for (const cookie of results.flat()) {
        const key = `${cookie.domain}|${cookie.path}|${cookie.name}`;
        if (seen.has(key)) continue;
        seen.add(key);
        cookies.push(cookie);
      }
      if (!cookies.length) throw new Error('Tidak ada cookie yang terbaca.');

      const hasSession = cookies.some((c) => c.name === 'sessionid');
      download(toNetscape(cookies));
      button.textContent = hasSession ? 'Tersimpan' : 'Tersimpan (tanpa sessionid)';
      if (!hasSession) {
        console.warn(
          'sessionid tidak terbaca. Aktifkan akses HttpOnly cookies: ' +
          'Tampermonkey (beta) Security > Allow scripts to access cookies > All, ' +
          'atau Violentmonkey > pengaturan script > allow HTTP-only cookies.',
        );
      }
    } catch (error) {
      console.error(error);
      button.textContent = 'Gagal - cek console';
    } finally {
      button.disabled = false;
      setTimeout(() => {
        button.textContent = previous;
      }, 2500);
    }
  }

  button.addEventListener('click', exportCookies);
  document.body.appendChild(button);
})();
