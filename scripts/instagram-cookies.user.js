// ==UserScript==
// @name         GoomysDL - Instagram Cookie Export
// @namespace    https://github.com/geoffreyoner/GoomysDL
// @version      1.1.0
// @description  Export instagram.com cookies as a Netscape cookies.txt for yt-dlp / GoomysDL.
// @author       geoffreyoner
// @match        https://www.instagram.com/*
// @match        https://instagram.com/*
// @grant        GM_cookie
// @grant        GM.cookie
// @run-at       document-idle
// @noframes
// ==/UserScript==

(() => {
  'use strict';

  const DOMAINS = ['https://www.instagram.com/', 'https://instagram.com/'];

  async function listCookies(details) {
    const errors = [];
    if (typeof GM !== 'undefined' && GM.cookie && GM.cookie.list) {
      try {
        return await GM.cookie.list(details);
      } catch (error) {
        errors.push(`GM.cookie: ${error.message || error}`);
      }
    }
    if (typeof GM_cookie !== 'undefined' && GM_cookie.list) {
      try {
        return await new Promise((resolve, reject) => {
          GM_cookie.list(details, (cookies, error) => {
            if (error) reject(new Error(error));
            else resolve(cookies || []);
          });
        });
      } catch (error) {
        errors.push(`GM_cookie: ${error.message || error}`);
      }
    }
    if (!errors.length) {
      errors.push('GM_cookie tidak tersedia. Pakai Tampermonkey atau Violentmonkey.');
    }
    throw new Error(errors.join(' | '));
  }

  function clean(value) {
    return String(value == null ? '' : value).replace(/[\t\r\n]/g, '');
  }

  function toNetscape(cookies) {
    const lines = [
      '# Netscape HTTP Cookie File',
      '# https://curl.se/docs/http-cookies.html',
      '# Generated by GoomysDL Instagram Cookie Export',
      '',
    ];
    for (const c of cookies) {
      if (!c || !c.name) continue;
      const domain = clean(c.domain);
      lines.push([
        domain,
        domain.startsWith('.') ? 'TRUE' : 'FALSE',
        clean(c.path) || '/',
        c.secure ? 'TRUE' : 'FALSE',
        c.expirationDate ? Math.floor(c.expirationDate) : 0,
        clean(c.name),
        clean(c.value),
      ].join('\t'));
    }
    return `${lines.join('\n')}\n`;
  }

  function download(text) {
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'instagram-cookies.txt';
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  const button = document.createElement('button');
  button.type = 'button';
  button.textContent = 'Export cookies.txt';
  button.title = 'Instagram cookies untuk yt-dlp / GoomysDL';
  Object.assign(button.style, {
    position: 'fixed',
    right: '16px',
    bottom: '16px',
    zIndex: '2147483647',
    padding: '10px 14px',
    border: '1px solid #444',
    borderRadius: '999px',
    background: '#111',
    color: '#eee',
    font: '600 12px system-ui, sans-serif',
    cursor: 'pointer',
    opacity: '0.85',
  });

  async function exportCookies() {
    const previous = button.textContent;
    button.disabled = true;
    button.textContent = 'Membaca cookie...';
    try {
      const results = await Promise.allSettled(
        DOMAINS.map((url) => listCookies({ url })),
      );
      const seen = new Set();
      const cookies = [];
      for (const result of results) {
        if (result.status !== 'fulfilled') continue;
        for (const cookie of result.value) {
          const key = `${cookie.domain}|${cookie.path}|${cookie.name}`;
          if (seen.has(key)) continue;
          seen.add(key);
          cookies.push(cookie);
        }
      }
      if (!cookies.length) {
        const reasons = results
          .filter((r) => r.status === 'rejected')
          .map((r) => r.reason?.message || String(r.reason));
        throw new Error(reasons.join(' | ') || 'Tidak ada cookie yang terbaca.');
      }

      const hasSession = cookies.some((c) => c.name === 'sessionid');
      download(toNetscape(cookies));
      button.textContent = hasSession ? 'Tersimpan' : 'Tersimpan (tanpa sessionid)';
      console.log(`[cookie export] ${cookies.length} cookie, sessionid: ${hasSession}`);
      if (!hasSession) {
        const hint =
          'sessionid tidak terbaca (HttpOnly). Aktifkan akses HttpOnly cookies:\n' +
          '- Tampermonkey beta: Security > Allow scripts to access cookies > All\n' +
          '- Violentmonkey 2.35.1+: setting global + per-script allow HTTP-only cookies';
        console.warn(hint);
        alert(hint);
      }
    } catch (error) {
      console.error(error);
      button.textContent = 'Gagal';
      alert(`Export gagal:\n${error.message || error}\n\nCek console untuk detail.`);
    } finally {
      button.disabled = false;
      setTimeout(() => {
        button.textContent = previous;
      }, 2500);
    }
  }

  console.log(
    '[cookie export] manager:',
    typeof GM_info === 'undefined' ? 'unknown' : `${GM_info.scriptHandler} ${GM_info.version}`,
    '| GM.cookie:', typeof GM !== 'undefined' && !!GM.cookie,
    '| GM_cookie:', typeof GM_cookie !== 'undefined',
  );

  button.addEventListener('click', exportCookies);
  document.body.appendChild(button);
})();
